class TestParseMarkdownFinding:
    def test_full_finding(self, tmp_path: Path) -> None:
        md = _write_finding(tmp_path, "abc-0.md", _finding_md())
        finding = parse_markdown_finding(md)
        assert finding is not None
        assert finding.finding_id == "abc-0"
        assert finding.file_path == Path("src/example.py")
        assert finding.line_start == 10
        assert finding.line_end == 15
        assert finding.existing_code == "old_code()"
        assert finding.suggested_code == "new_code()"
        assert finding.review_comment == "fix it"
        assert "Confirmed" in finding.analysis

    def test_missing_suggested_code(self, tmp_path: Path) -> None:
        md = _write_finding(
            tmp_path, "no-sug-0.md", _finding_md(suggested=None)
        )
        finding = parse_markdown_finding(md)
        assert finding is not None
        assert finding.suggested_code == ""

    def test_missing_required_sections(self, tmp_path: Path) -> None:
        path = _write_finding(tmp_path, "bad.md", "# empty\n")
        assert parse_markdown_finding(path) is None

    def test_nonexistent_file(self) -> None:
        assert parse_markdown_finding(Path("/nonexistent/file.md")) is None


class TestGetVerdict:
    def test_valid(self, tmp_path: Path) -> None:
        md = _write_finding(tmp_path, "v.md", _finding_md(verdict="VALID"))
        assert get_verdict(md) == "VALID"

    def test_rejected(self, tmp_path: Path) -> None:
        md = _write_finding(tmp_path, "r.md", _finding_md(verdict="REJECTED"))
        assert get_verdict(md) == "REJECTED"

    def test_backlog(self, tmp_path: Path) -> None:
        md = _write_finding(tmp_path, "b.md", _finding_md(verdict="BACKLOG"))
        assert get_verdict(md) == "BACKLOG"

    def test_missing_verdict(self, tmp_path: Path) -> None:
        path = _write_finding(tmp_path, "n.md", "# no verdict\n")
        assert get_verdict(path) is None

    def test_nonexistent(self) -> None:
        assert get_verdict(Path("/nonexistent/file.md")) is None

    def test_is_valid_finding(self, tmp_path: Path) -> None:
        good = _write_finding(tmp_path, "g.md", _finding_md(verdict="VALID"))
        bad = _write_finding(tmp_path, "b.md", _finding_md(verdict="REJECTED"))
        assert is_valid_finding(good) is True
        assert is_valid_finding(bad) is False


