class TestLoadFeedbackDir:
    def test_missing_dir(self, tmp_path: Path) -> None:
        with pytest.raises(FileNotFoundError):
            load_feedback_dir(tmp_path / "nope")

    def test_not_a_directory(self, tmp_path: Path) -> None:
        f = tmp_path / "file.txt"
        f.write_text("x", encoding="utf-8")
        with pytest.raises(NotADirectoryError):
            load_feedback_dir(f)

    def test_empty_dir(self, tmp_path: Path) -> None:
        report = load_feedback_dir(tmp_path)
        assert report.findings == []
        assert report.counts == {}
        assert report.summary_text is None

    def test_skips_non_finding_files(self, tmp_path: Path) -> None:
        for name in NON_FINDING_FILES:
            (tmp_path / name).write_text(f"# {name}\n", encoding="utf-8")
        _write_finding(
            tmp_path,
            "keep-0.md",
            _finding_md(verdict="VALID", analysis="real finding"),
        )
        report = load_feedback_dir(tmp_path)
        assert len(report.findings) == 1
        assert report.findings[0].finding_id == "keep-0"
        assert report.summary_text is not None
        assert "SUMMARY.md" in report.summary_text or report.summary_text.startswith("#")

    def test_counts_and_grouping(self, tmp_path: Path) -> None:
        (tmp_path / "SUMMARY.md").write_text(
            "# Review Analysis Summary\n\nCoding agent: opencode (standard/coder)\n",
            encoding="utf-8",
        )
        _write_finding(
            tmp_path,
            "a-0.md",
            _finding_md(
                file_path="b/file.py",
                lines="20-22",
                verdict="VALID",
                analysis="valid A",
            ),
        )
        _write_finding(
            tmp_path,
            "b-1.md",
            _finding_md(
                file_path="a/file.py",
                lines="1-2",
                verdict="VALID",
                analysis="valid B",
            ),
        )
        _write_finding(
            tmp_path,
            "c-2.md",
            _finding_md(verdict="REJECTED", analysis="rejected"),
        )
        _write_finding(
            tmp_path,
            "d-3.md",
            _finding_md(verdict="BACKLOG", analysis="later"),
        )

        report = load_feedback_dir(tmp_path)
        assert len(report.findings) == 4
        assert report.counts == {"VALID": 2, "REJECTED": 1, "BACKLOG": 1}
        assert report.summary_text is not None
        assert "opencode" in report.summary_text

        # VALID first, then within VALID sort by source_file
        assert [f.verdict for f in report.findings] == [
            "VALID",
            "VALID",
            "REJECTED",
            "BACKLOG",
        ]
        valid = findings_for_verdict(report, "VALID")
        assert len(valid) == 2
        assert valid[0].source_file == "a/file.py"
        assert valid[1].source_file == "b/file.py"

    def test_degraded_partial_finding(self, tmp_path: Path) -> None:
        """Files that only have a verdict still appear (UNKNOWN path degraded)."""
        content = (
            "# OCR Review Analysis\n\n"
            "## LLM Analysis\n\n"
            "**Verdict**: BACKLOG\n\n"
            "**Analysis**:\n"
            "opencode execution timed out (>120s)\n"
        )
        _write_finding(tmp_path, "timeout-0.md", content)
        report = load_feedback_dir(tmp_path)
        assert len(report.findings) == 1
        f = report.findings[0]
        assert f.verdict == "BACKLOG"
        assert f.source_file == "(unknown)"
        assert "timed out" in f.raw_markdown

    def test_review_finding_dataclass(self) -> None:
        finding = ReviewFinding(
            file_path=Path("src/test.py"),
            line_start=1,
            line_end=10,
            existing_code="old",
            suggested_code="new",
            review_comment="fix this",
            analysis="it's broken",
            finding_id="test-0",
        )
        assert finding.finding_id == "test-0"


